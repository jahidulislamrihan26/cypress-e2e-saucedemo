// Builds docs/traceability.md: which cases of the manual test suite (manual-testing-saucedemo repository) this project automates.
// A test is linked to a manual case by [TC-nnn] in its title and to a defect by [BUG-nnn].   Usage: node tools/trace.js
const fs = require('fs');
const path = require('path');
const { parseCsv } = require('./csv');

const ROOT = path.join(__dirname, '..');
const SPECS = path.join(ROOT, 'cypress', 'e2e');
const [head, ...body] = parseCsv(fs.readFileSync(path.join(ROOT, 'data', 'manual-test-cases.csv'), 'utf8')).filter((r) => r.length > 1);
const col = (n) => head.indexOf(n);
const manual = body.map((r) => ({ id: r[col('ID')], title: r[col('Title')], status: r[col('Status')], defect: r[col('Defect')] }));

// Every line of every spec that names a manual case (comment lines are ignored).
const found = {};
let definitions = 0;
for (const file of fs.readdirSync(SPECS).filter((f) => f.endsWith('.cy.js')).sort()) {
  fs.readFileSync(path.join(SPECS, file), 'utf8').split('\n').forEach((line, i) => {
    if (/^\s*\/\//.test(line)) return;
    if (/\bit\(/.test(line)) definitions++;
    for (const m of line.matchAll(/TC-\d{3}/g)) {
      (found[m[0]] = found[m[0]] || []).push({ file, line: i + 1, known: /BUG-\d+|known defect/i.test(line), bug: (line.match(/BUG-\d+/) || [])[0] });
    }
  });
}
const manualIds = new Set(manual.map((m) => m.id));
const unknown = Object.keys(found).filter((id) => !manualIds.has(id));

const rows = manual.map((m) => {
  const hits = found[m.id] || [];
  const state = hits.length ? (hits.every((h) => h.known) ? 'Automated, known defect' : 'Automated') : 'Manual only';
  return { ...m, hits, state };
});
const n = (s) => rows.filter((r) => r.state === s).length;
const automated = n('Automated') + n('Automated, known defect');
const defectsCovered = new Set(Object.values(found).flat().map((h) => h.bug).filter(Boolean));

const L = [];
L.push('# Traceability: manual test cases to Cypress tests', '');
L.push('Generated by `npm run trace` from the manual suite ([test-cases.csv](https://github.com/jahidulislamrihan26/manual-testing-saucedemo/blob/main/test-suite/test-cases.csv), snapshot in data/manual-test-cases.csv) and the spec files. A test is linked to a manual case by `[TC-nnn]` in its title and to a defect by `[BUG-nnn]`.', '');
L.push(`**${automated} of ${rows.length} manual cases (${Math.round((100 * automated) / rows.length)}%) have at least one Cypress test.** ${defectsCovered.size} of the 20 logged defects are captured as known-defect tests.`, '');
L.push('| Result | Manual cases |', '|---|---|', `| Automated (passing check) | ${n('Automated')} |`, `| Automated, captures a known defect | ${n('Automated, known defect')} |`, `| Manual only | ${n('Manual only')} |`, '');
L.push('| Manual case | Title | Manual result | Automated | Where |', '|---|---|---|---|---|');
for (const r of rows) {
  const where = r.hits.slice(0, 3).map((h) => `${h.file}:${h.line}`).join(', ') + (r.hits.length > 3 ? `, +${r.hits.length - 3} more` : '');
  const bugs = [...new Set(r.hits.map((h) => h.bug).filter(Boolean))];
  L.push(`| ${r.id} | ${r.title.replace(/\|/g, '\\|')} | ${r.status}${r.defect ? ` (${r.defect})` : ''} | ${r.state}${bugs.length ? ` ${bugs.join(', ')}` : ''} | ${r.hits.length ? where : '-'} |`);
}
const manualOnly = rows.filter((r) => r.state === 'Manual only');
L.push('', '## Manual only, and why', '');
L.push('These cases need something Cypress does not do well, or are covered by the [Playwright project](https://github.com/jahidulislamrihan26/playwright-ui-automation-pom) for the same site:', '');
for (const r of manualOnly) L.push(`- **${r.id}** ${r.title}`);
if (unknown.length) L.push('', `**Warning:** these ids appear in specs but not in the manual suite: ${unknown.join(', ')}`);
fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs', 'traceability.md'), L.join('\n') + '\n');
console.log(`Traceability: ${automated}/${rows.length} cases automated, ${defectsCovered.size} defects covered, ${definitions} test definitions, ${manualOnly.length} manual only${unknown.length ? `, WARNING unknown ids: ${unknown.join(', ')}` : ''}`);
